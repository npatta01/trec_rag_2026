def test_the_script_requires_uv_on_path(tmp_path: Path) -> None:
    """With nothing on PATH, the missing-uv message is what the reader gets.

    The script must reach its own diagnostic before it needs any external
    command, so this points PATH at an empty directory rather than curating one
    that happens to hold the right coreutils.
    """
    empty_bin = tmp_path / "empty-bin"
    empty_bin.mkdir()
    env = dict(os.environ)
    env["PATH"] = str(empty_bin)
    process = subprocess.run(
        [BASH, str(VERIFY_TORCH_GROUPS)],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )

    assert process.returncode == 1
    assert "uv is required" in process.stderr
