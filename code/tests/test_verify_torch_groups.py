def _cuda_export(torch_line: str, *, nvidia_runtime: bool = True) -> str:
    body = [
        "# This file was autogenerated by uv via the following command:",
        "#    uv export --frozen --group cuda --no-hashes",
        "-e .",
        "numpy==2.5.1 ; python_full_version == '3.12.*' and sys_platform == 'linux'",
        "sentence-transformers==5.6.0 ; python_full_version == '3.12.*'",
        torch_line,
        "transformers==5.13.0 ; python_full_version == '3.12.*'",
    ]
    if nvidia_runtime:
        body.extend(NVIDIA_RUNTIME_LINES.splitlines())
    return "\n".join(body) + "\n"


GOOD_CUDA_TORCH = "torch==2.9.1 ; python_full_version == '3.12.*' and sys_platform == 'linux'"

# The PEP 751 rendering of the same export. Unlike a requirements line, it
# records the index each package was resolved from, which is the only thing that
# can tell `torch==2.9.1` from PyPI apart from `torch==2.9.1` from a mirror.
PYLOCK_HEADER = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --group cuda --format pylock.toml
lock-version = "1.0"
created-by = "uv"
requires-python = "==3.12.*"

[[packages]]
name = "numpy"
version = "2.5.1"
index = "https://pypi.org/simple"
wheels = [
    { name = "numpy-2.5.1-cp312-cp312-manylinux_2_27_x86_64.whl", url = "https://files.pythonhosted.org/packages/aa/numpy-2.5.1-cp312-cp312-manylinux_2_27_x86_64.whl", hashes = { sha256 = "1111" } },
]
"""

PYPI_INDEX = "https://pypi.org/simple"


def _torch_pylock_package(
    *,
    version: str = "2.9.1",
    index: str | None = PYPI_INDEX,
    wheel_url: str = (
        "https://files.pythonhosted.org/packages/bb/"
        "torch-2.9.1-cp312-cp312-manylinux_2_28_x86_64.whl"
    ),
    subtable_wheels: bool = False,
) -> str:
    """One `[[packages]]` block for torch, rendered the way uv renders them.

    ``index=None`` is what a direct-URL wheel looks like: no index key at all.
    ``subtable_wheels`` switches the wheel list from an inline array to
    ``[[packages.wheels]]`` sub-tables, whose own column-0 ``name`` key must not
    be read as the package's name.
    """
    wheel_name = f"torch-{version}-cp312-cp312-manylinux_2_28_x86_64.whl"
    lines = ["[[packages]]", 'name = "torch"', f'version = "{version}"']
    if index is not None:
        lines.append(f'index = "{index}"')
    if subtable_wheels:
        lines.extend(
            [
                "",
                "[[packages.wheels]]",
                f'name = "{wheel_name}"',
                f'url = "{wheel_url}"',
                'hashes = { sha256 = "2222" }',
            ]
        )
    else:
        lines.extend(
            [
                "wheels = [",
                f'    {{ name = "{wheel_name}", url = "{wheel_url}", '
                'hashes = { sha256 = "2222" } },',
                "]",
            ]
        )
    return "\n".join(lines) + "\n"


def _cuda_pylock(*torch_packages: str) -> str:
    packages = torch_packages or (_torch_pylock_package(),)
    return PYLOCK_HEADER + "\n" + "\n".join(packages)


# uv's own wording when the committed lock cannot serve the request.
STALE_LOCK_CHECK_ERROR = (
    "error: The lockfile at `uv.lock` needs to be updated, but `--locked` was provided. "
    "To update the lockfile, run `uv lock`.\n"
)
STALE_EXPORT_ERROR = (
    "error: The lockfile at `uv.lock` needs to be updated, but `--frozen` was provided. "
    "To update the lockfile, run `uv lock`.\n"
)


class Result:
    """A completed verifier run plus the uv invocations it made."""

    def __init__(self, process: subprocess.CompletedProcess[str], invocations: list[list[str]]):
        self.returncode = process.returncode
        self.stdout = process.stdout
        self.stderr = process.stderr
        self.invocations = invocations

    @property
    def output(self) -> str:
        return self.stdout + self.stderr

    def subcommands(self) -> list[str]:
        """The uv subcommand of each invocation, ignoring the global flags."""
        found = []
        for argv in self.invocations:
            skip_value = False
            for token in argv:
                if skip_value:
                    skip_value = False
                    continue
                if token == "--cache-dir":
                    skip_value = True
                    continue
                if not token.startswith("-"):
                    found.append(token)
                    break
        return found


def _run_verifier(tmp_path: Path, fixture: dict[str, object]) -> Result:
    stub_dir = tmp_path / "stub-bin"
    stub_dir.mkdir()
    stub = stub_dir / "uv"
    stub.write_text(STUB_UV.format(python=sys.executable), encoding="utf-8")
    stub.chmod(0o755)

    fixture_path = tmp_path / "fixture.json"
    fixture_path.write_text(json.dumps(fixture), encoding="utf-8")
    log_path = tmp_path / "uv-invocations.jsonl"

    scratch_tmp = tmp_path / "scratch-tmp"
    scratch_tmp.mkdir()

    env = dict(os.environ)
    env["PATH"] = f"{stub_dir}{os.pathsep}{env.get('PATH', '')}"
    env["STUB_UV_FIXTURE"] = str(fixture_path)
    env["STUB_UV_LOG"] = str(log_path)
    # Any cache directory the script creates lands here, not in a shared one.
    env["TMPDIR"] = str(scratch_tmp)

    process = subprocess.run(
        [BASH, str(VERIFY_TORCH_GROUPS)],
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    logged = log_path.read_text(encoding="utf-8") if log_path.exists() else ""
    invocations = [json.loads(line) for line in logged.splitlines() if line.strip()]
    return Result(process, invocations)


def _fixture(
    *,
    lock: dict[str, object] | None = None,
    rocm: dict[str, object] | None = None,
    cuda: dict[str, object] | None = None,
    cuda_pylock: dict[str, object] | None = None,
) -> dict[str, object]:
    return {
        "lock": lock if lock is not None else {"returncode": 0},
        "exports": {
            "rocm": rocm if rocm is not None else {"returncode": 0, "stdout": ROCM_EXPORT},
            "cuda": (
                cuda
                if cuda is not None
                else {"returncode": 0, "stdout": _cuda_export(GOOD_CUDA_TORCH)}
            ),
        },
        # Only the cuda group's source is proved this way, so the rocm group has
        # no pylock fixture: if the script ever asked for one, the stub would
        # fail the run instead of quietly answering.
        "pylock": {
            "cuda": (
                cuda_pylock
                if cuda_pylock is not None
                else {"returncode": 0, "stdout": _cuda_pylock()}
            ),
        },
    }


def test_both_groups_pass_on_the_intended_torch_builds(tmp_path: Path) -> None:
    result = _run_verifier(tmp_path, _fixture())

    assert result.returncode == 0, result.output
    assert "OK   uv.lock is current with pyproject.toml" in result.stdout
    assert "OK   rocm: torch @ https://repo.radeon.com/" in result.stdout
    assert "OK   cuda: torch==2.9.1 from https://pypi.org/simple" in result.stdout
    assert "Both hardware groups select their intended torch source." in result.stdout


def test_lock_currency_is_proved_without_installing(tmp_path: Path) -> None:
    """Currency comes from `uv lock --check`, and nothing may install."""
    result = _run_verifier(tmp_path, _fixture())

    assert result.subcommands() == ["lock", "export", "export", "export"]
    lock_argv = result.invocations[0]
    assert "--check" in lock_argv
    installing = {"sync", "add", "remove", "pip", "run", "tool", "build", "install"}
    assert not installing.intersection(result.subcommands())
    for argv in result.invocations[1:]:
        assert "--frozen" in argv, argv


def test_no_uv_call_may_provision_an_interpreter(tmp_path: Path) -> None:
    """The interpreter is the one install `--no-cache` alone would not prevent.

    This project pins Python 3.12.13. On a host without it, `uv lock` will fetch
    and install a managed interpreter just to resolve — silently, and outside
    the throwaway cache directory. `--no-python-downloads` turns that into a
    loud failure, which is what makes "installs nothing" true rather than true
    only on hosts that happen to already have the pinned Python.
    """
    result = _run_verifier(tmp_path, _fixture())

    assert result.invocations, "the verifier made no uv calls"
    for argv in result.invocations:
        assert "--no-python-downloads" in argv, argv


def test_the_cuda_source_proof_reads_a_group_scoped_pylock_export(tmp_path: Path) -> None:
    """Source comes from PEP 751 metadata scoped to the group, not from uv.lock."""
    result = _run_verifier(tmp_path, _fixture())

    pylock_calls = [argv for argv in result.invocations if "--format" in argv]
    assert len(pylock_calls) == 1, result.invocations
    argv = pylock_calls[0]
    assert argv[argv.index("--format") + 1] == "pylock.toml"
    # Scoped to cuda: an unscoped multi-fork uv.lock block is not what is parsed.
    assert argv[argv.index("--group") + 1] == "cuda"
    assert "--frozen" in argv
    assert "--no-cache" in argv
    assert "--no-python-downloads" in argv
    assert not any("uv.lock" in token for token in argv), argv


def test_every_uv_call_avoids_the_persistent_cache(tmp_path: Path) -> None:
    result = _run_verifier(tmp_path, _fixture())

    for argv in result.invocations:
        assert "--no-cache" in argv, argv
        cache_dir = Path(argv[argv.index("--cache-dir") + 1])
        assert tmp_path in cache_dir.parents, cache_dir
        assert cache_dir.name.startswith("verify-torch-groups-uv-cache."), cache_dir
    # The throwaway cache directory does not survive the run.
    leftovers = [
        entry
        for entry in (tmp_path / "scratch-tmp").iterdir()
        if entry.name.startswith("verify-torch-groups-uv-cache.")
    ]
    assert leftovers == []


