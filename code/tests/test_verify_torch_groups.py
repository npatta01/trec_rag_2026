@pytest.mark.parametrize(
    ("label", "stderr"),
    [
        ("unsupported flag", "error: unexpected argument '--check' found\n"),
        (
            "authentication",
            "error: Failed to fetch `https://pypi.org/simple/torch/`\n"
            "  Caused by: HTTP status client error (401 Unauthorized)\n",
        ),
        (
            "network",
            "error: Failed to fetch `https://pypi.org/simple/torch/`\n"
            "  Caused by: dns error: failed to lookup address information\n",
        ),
    ],
)
def test_an_unverifiable_lock_is_not_reported_as_stale(
    tmp_path: Path, label: str, stderr: str
) -> None:
    """None of these say anything about the lock's currency.

    Telling the reader to regenerate it would send them to re-resolve against
    the very index the run could not reach, so the hint must stay unprinted.
    """
    result = _run_verifier(
        tmp_path,
        _fixture(lock={"returncode": 2, "stderr": stderr}),
    )

    assert result.returncode == 1, label
