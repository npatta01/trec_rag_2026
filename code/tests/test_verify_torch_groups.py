"""Contract tests for ``code/tools/verify_torch_groups.sh``.

Hermetic: every test runs the real script against a **stub ``uv``** placed first
on ``PATH``, so nothing resolves, downloads, installs, or reads the committed
``uv.lock``. The only files written are inside pytest's ``tmp_path`` (the stub,
its fixture, its invocation log, and the throwaway uv cache directory the script
creates under a redirected ``TMPDIR``). No shared, persistent cache is touched.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

import pytest


ROOT = Path(__file__).resolve().parents[2]
VERIFY_TORCH_GROUPS = ROOT / "code" / "tools" / "verify_torch_groups.sh"
# Resolved against the real PATH: the tests hand the script a doctored PATH.
BASH = shutil.which("bash")

pytestmark = pytest.mark.skipif(BASH is None, reason="bash is required to run the verifier")

STUB_UV = '''#!{python}
"""Stand in for uv: answer from a JSON fixture and record every invocation."""
import json
import os
import sys
from pathlib import Path

argv = sys.argv[1:]
fixture = json.loads(Path(os.environ["STUB_UV_FIXTURE"]).read_text(encoding="utf-8"))
with Path(os.environ["STUB_UV_LOG"]).open("a", encoding="utf-8") as handle:
    handle.write(json.dumps(argv) + "\\n")


def emit(entry):
    sys.stdout.write(entry.get("stdout", ""))
    sys.stderr.write(entry.get("stderr", ""))
    raise SystemExit(int(entry.get("returncode", 0)))


if "lock" in argv:
    emit(fixture.get("lock", {{"returncode": 0}}))
if "export" in argv:
    group = argv[argv.index("--group") + 1]
    fmt = argv[argv.index("--format") + 1] if "--format" in argv else "requirements.txt"
    section = "pylock" if fmt == "pylock.toml" else "exports"
    entry = fixture.get(section, {{}}).get(group)
    if entry is None:
        emit({{
            "returncode": 2,
            "stderr": "error: no " + section + " fixture for group " + group + chr(10),
        }})
    emit(entry)
emit({{"returncode": 2, "stderr": "error: unexpected uv invocation " + json.dumps(argv) + chr(10)}})
'''

