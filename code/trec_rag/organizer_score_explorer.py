def render_html(payload: dict, generated: str) -> str:
    """Return the standalone explorer page."""
    data = json.dumps(payload, separators=(",", ":"), sort_keys=True)
    # Keep the JSON inert inside the <script> block.
    data = data.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    return _TEMPLATE.replace("__DATA__", data).replace("__GENERATED__", _esc(generated))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo_root", nargs="?", default=".", type=Path)
    parser.add_argument("-o", "--output", type=Path, default=None)
    parser.add_argument("--generated", default="2026-11-08")
    args = parser.parse_args(argv)

    repo_root = args.repo_root.resolve()
    org_root = repo_root / "submissions/trec-rag-2026/organizer-results"
